# Entrada
numero_um = int(input('Digite o primeiro número: '))
numero_dois = int(input('Digite o segundo número: '))

# Processamento 
soma = numero_um + numero_dois
subtracao = numero_um - numero_dois
divisao = soma / subtracao 

# Saída
print(f'A divisão da soma dos números {numero_um} e {numero_dois} pela sua subtração é igual a {divisao}.')