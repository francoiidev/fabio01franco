# Entrada
valor_horas = int(input('Digite as horas: '))
valor_minutos = int(input('Digite os minutos: '))

# Processamento
valor_final = valor_horas * 60 + valor_minutos

# Saída 
print(f'O valor de {valor_horas} horas e {valor_minutos} minutos, em minutos, é de {valor_final} minutos.')

